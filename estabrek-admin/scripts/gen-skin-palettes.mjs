// Generates src/theme/skin-palettes.css: the status colours (emerald, red, sky…)
// flipped for the light "rose" skin, so text shades that were made for a dark
// background (300/400) become dark shades that read well on cream.
// Run: node scripts/gen-skin-palettes.mjs
import fs from "node:fs";
import colors from "tailwindcss/colors.js";
import { SKIN_PALETTES } from "./skin-palettes.list.mjs";

const rgb = (hex) => {
  const h = hex.replace("#", "");
  const n = parseInt(h.length === 3 ? h.split("").map((c) => c + c).join("") : h, 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};
// Light-text shades become dark text; tints used as dark panels become light panels;
// the solid button shades (500/600) stay as they are.
const FLIP = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 700, 500: 500, 600: 600, 700: 300, 800: 200, 900: 100, 950: 50 };

let out = "/* Generated by scripts/gen-skin-palettes.mjs — do not edit by hand. */\n";
out += ':root[data-skin="rose"] {\n';
for (const p of SKIN_PALETTES) {
  for (const [shade, to] of Object.entries(FLIP)) {
    const hex = colors[p][to];
    if (hex && hex.startsWith("#")) out += `  --sk-${p}-${shade}: ${rgb(hex)};\n`;
  }
}
out += "}\n";
fs.writeFileSync(new URL("../src/theme/skin-palettes.css", import.meta.url), out);
console.log("written", out.split("\n").length, "lines");
