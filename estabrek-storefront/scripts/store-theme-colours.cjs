// Lists every colour the rose stylesheet uses (as postcss/theme-tokens.cjs names them) into
// src/storeThemes/roseColours.gen.ts. Run after changing colours in cinematic.css:
//   node scripts/store-theme-colours.cjs
// tests/store-themes.spec.ts fails when the list is out of date.
const fs = require("fs");
const path = require("path");
const postcss = require("postcss");
const tokens = require("../postcss/theme-tokens.cjs");

const file = path.join(__dirname, "../src/app/cinematic.css");
postcss([tokens()])
  .process(fs.readFileSync(file, "utf8"), { from: file })
  .then(({ css }) => {
    // Also the colours the rose design sets from code (roseVar in roseDesign.ts: the scene palettes).
    const design = fs.readFileSync(path.join(__dirname, "../src/components/cinematic/roseDesign.ts"), "utf8");
    const scenes = ((design.match(/rosePalettes[^=]*=\s*\{([^}]*)\}/) || [])[1] || "").match(/#[0-9a-f]{6}/gi) || [];
    const fromCss = (css.match(/--st-([0-9a-f]{6})\b/g) || []).map((x) => x.slice(5));
    const list = [...new Set([...fromCss, ...scenes.map((h) => h.slice(1).toLowerCase())])].sort();
    const out = `// Generated by scripts/store-theme-colours.cjs from src/app/cinematic.css: do not edit.\nexport const ROSE_COLOURS = ${JSON.stringify(list)} as const;\n`;
    fs.writeFileSync(path.join(__dirname, "../src/storeThemes/roseColours.gen.ts"), out);
    console.log(`${list.length} colours`);
  });
