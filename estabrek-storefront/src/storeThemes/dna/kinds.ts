/**
 * The kinds of store (phase 11), each with a design of its own made for it: its DNA on every
 * axis (axes.ts), the colours it starts from, a signature section no other design has, and
 * the second layout of its "another layout" variant. distance.ts keeps them apart from each
 * other and from the rose design (Estabrek's own); tests/store-designs.spec.ts checks it.
 *
 * Written short: the DNA as its words in the order of DNA_ORDER, the colours as
 * "mode page brand stand-out words", the other layout as "opening pictures".
 */
import type { DNA, Sector, StoreKind, Words } from "./axes";

export const DNA_ORDER = ["archetype", "type", "colours", "shape", "surface", "imagery", "icons", "motion", "motif", "card", "header", "footer", "voice"] as const;
const w = (ar: string, en: string, he: string): Words => ({ ar, en, he });
function k(id: string, sector: Sector, name: [string, string, string], dna: string, seed: string, sig: [string, string, string, string], alt: string): StoreKind {
  const d = dna.trim().split(/\s+/);
  const [mode, bg, accent, strong, ink] = seed.trim().split(/\s+/);
  const [archetype, imagery] = alt.trim().split(/\s+/);
  const out = Object.fromEntries(DNA_ORDER.map((x, i) => [x, d[i]])) as unknown as DNA;
  return {
    id, sector, name: w(...name),
    dna: { ...out, seed: { mode: mode as "light" | "dark", bg, accent, strong, ink } },
    signature: { id: sig[0], name: w(sig[1], sig[2], sig[3]) },
    alt: { archetype: archetype as DNA["archetype"], imagery: imagery as DNA["imagery"] },
  };
}

