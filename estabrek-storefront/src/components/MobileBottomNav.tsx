interface NavItem {
  href: string;
  label: string;
  icon: (props: { active?: boolean }) => React.ReactNode;
  badge?: number;
}

export function MobileBottomNav() {
  const pathname = usePathname();
  const { count: cartCount } = useCart();
  const { count: wishlistCount } = useWishlist();

  const navItems: NavItem[] = [
    { href: "/", label: "الرئيسية", icon: HomeIcon },
    { href: "/shop", label: "المتجر", icon: ShopIcon },
    { href: "/search", label: "البحث", icon: SearchIcon },
    { href: "/wishlist", label: "المفضلة", icon: HeartIcon, badge: wishlistCount },
    { href: "/cart", label: "السلة", icon: CartIcon, badge: cartCount },
  ];

  const isActive = (href: string) => {
    if (href === "/") return pathname === "/";
    return pathname.startsWith(href);
  };

  return (
    <nav className="mobile-bottom-nav" dir="rtl">
      {navItems.map((item) => {
        const active = isActive(item.href);
        return (
          <Link
            key={item.href}
            href={item.href}
            className={`mobile-nav-item ${active ? "active" : ""}`}
          >
            <div className="mobile-nav-icon">
              {item.icon({ active })}
              {item.badge && item.badge > 0 && (
                <span className="mobile-nav-badge">{item.badge > 99 ? "99+" : item.badge}</span>
              )}
            </div>
            <span className="mobile-nav-label">{item.label}</span>
            {active && <span className="mobile-nav-indicator" />}
          </Link>
        );
      })}
    </nav>
  );
}
