test("studio changes card controls and simulates rules without reloading its document or touching a real cart", async ({ page }) => {
  test.setTimeout(120000);
  await page.goto("http://127.0.0.1:5178/tests/fixtures/editor-controls.html?lang=en&commerce=shop");
  const frame = page.frameLocator('[data-testid="studio-frame"]');
  await expect(frame.locator('[data-tree-node="commerce-shop"]')).toBeVisible();
  await frame.locator('[data-tree-node="commerce-shop"]').evaluate(() => { (window as any).__retainedVisual = true; });
  await page.getByRole("tab", { name: "Layers", exact: true }).click();
  await page.locator('[data-testid="studio-layer"][data-node="commerce-shop"]').click();
  await page.getByTestId("card-design-mode").selectOption("custom");
  await expect(page.getByTestId("card-swatchSize")).toBeEnabled();
  await page.getByTestId("card-swatchSize").click();
  await page.getByTestId("card-swatchSize").press("ControlOrMeta+A");
  await page.getByTestId("card-swatchSize").pressSequentially("34");
  await page.getByTestId("card-swatchSize").press("Tab");
  await expect(frame.locator('[data-card-part="swatches"] button').first()).toHaveCSS("width", "34px");
  await page.getByTestId("interaction-cartAdded-mode").selectOption("custom");
  await page.getByTestId("interaction-cartAdded-add").click();
  await expect.poll(() => page.evaluate(() => (window as any).__canvasHarness.getNode("commerce-shop")?.node?.props?.interactions?.bindings?.cartAdded?.length)).toBe(1);
  await page.getByTestId("interaction-cartAdded-test").click();
  await expect(frame.locator(".cinematic-shell")).toHaveCSS("--selection-seed", "#806080");
  expect(await frame.locator("body").evaluate(() => (window as any).__retainedVisual)).toBe(true);
  expect(await frame.locator("body").evaluate(() => localStorage.getItem("estabrak_cart_v1"))).toBeNull();
});
