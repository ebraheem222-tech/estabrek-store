import { expect, test, type Page } from "@playwright/test";
async function configure(page: Page, patch = {}) {
  await page.request.post("http://127.0.0.1:4100/__test/commerce", { data: { on: true, ...patch } });
  await page.request.post("/api/revalidate", { headers: { "x-revalidate-secret": "fixture-publishing-only" }, data: { tags: ["cms", "cms:pages", "cms:bootstrap", "settings"], paths: ["/shop"] } });
}
test.afterEach(async ({ page }) => { await configure(page, { on: false }); });
test("a theme action clears a real hover preview before taking its reset snapshot", async ({ page }) => {
  await configure(page, { visualControls: { version: 1, revision: 1, interactions: { version: 1, bindings: { cartClick: [{ type: "theme", color: "#123456" }], colorChange: [{ type: "themeReset" }] } } } });
  await page.goto("/");
  const shell = page.locator(".cinematic-shell"), header = page.locator(".atelier-header");
  const button = page.locator(".rose-quick-add button").first();
  await button.scrollIntoViewIfNeeded(); await page.mouse.move(5, 180);
  await page.waitForTimeout(1200); // let the scroll scene's hand-back finish before recording its resting colour
  const before = await header.evaluate(el => (el as HTMLElement).style.getPropertyValue("--selection-seed"));
  await button.hover(); await expect(shell).toHaveAttribute("data-theme-preview", "true");
  await button.click();
  await expect(header).toHaveCSS("--selection-seed", "#123456");
  await expect(shell).not.toHaveAttribute("data-theme-preview", /.*/);
  const dialog = page.getByRole("dialog"); await expect(dialog).toBeVisible();
  await dialog.getByRole("radio").first().click();
  await expect.poll(() => header.evaluate(el => (el as HTMLElement).style.getPropertyValue("--selection-seed"))).toBe(before);
});
test("original-card colour overrides work without browser focus and survive quick-view portal actions", async ({ page }) => {
  await configure(page, { visualControls: { version: 1, revision: 1, interactions: { version: 1, bindings: { colorChange: [{ type: "theme", color: "#ff0000" }], click: [{ type: "theme", color: "#00ff00" }], cartAdded: [{ type: "theme", color: "#0000ff" }] } } }, shopProps: { interactions: { version: 1, bindings: { colorChange: [], click: [], cartAdded: [] } } } });
  await page.goto("/en/shop");
  const card = page.locator(".product-card-3d").first();
  const shell = page.locator(".cinematic-shell");
  const before = await shell.evaluate(el => (el as HTMLElement).style.getPropertyValue("--selection-seed"));
  await card.locator("button.color-swatch").last().evaluate((button: HTMLButtonElement) => { (document.activeElement as HTMLElement)?.blur(); button.click(); });
  expect(await shell.evaluate(el => (el as HTMLElement).style.getPropertyValue("--selection-seed"))).toBe(before);
  await card.getByRole("button", { name: "Quick preview", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toBeVisible();
  await dialog.getByRole("radio").last().click();
  await dialog.getByRole("button", { name: "Add to bag", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(await shell.evaluate(el => (el as HTMLElement).style.getPropertyValue("--selection-seed"))).toBe(before);
});
