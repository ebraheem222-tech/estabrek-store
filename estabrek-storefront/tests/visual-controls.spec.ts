test("global cards render catalog swatches, preserve a selected colour for quick add and separate cart events", async ({ page }) => {
  await configure(page, { visualControls: { version: 1, revision: 1, cardDesign: { layout: "horizontal", swatchSize: 32, swatchShape: "square", background: "#eeffee", titleSize: 23 }, interactions: { version: 1, bindings: { colorChange: [{ type: "theme", color: "event" }], cartClick: [{ type: "theme", color: "#123456" }], cartAdded: [{ type: "theme", color: "#654321" }] } } } });
  await page.goto("/en/shop");
  const card = page.locator(".configured-product-card").first();
  await expect(card).toHaveCSS("background-color", "rgb(238, 255, 238)");
  await expect(card.locator('[data-card-part="title"]')).toHaveCSS("font-size", "23px");
  const swatches = card.locator('[data-card-part="swatches"] button');
  await expect(swatches.first()).toHaveCSS("width", "32px");
  await swatches.last().click();
  const picked = await swatches.last().getAttribute("aria-label");
  await expect(swatches.last()).toHaveAttribute("aria-pressed", "true");
  await card.locator('[data-card-part="button"] button').click();
  const dialog = page.locator(".rose-sheet, .quick-add-layer").first();
  await expect(dialog).toBeVisible();
  await expect(page.locator(".cinematic-shell")).toHaveCSS("--selection-seed", "#123456");
  await expect(dialog.getByRole("radio", { name: picked!, exact: true })).toBeChecked();
  await dialog.getByRole("button", { name: "Add to bag", exact: true }).click();
  await expect(page.locator(".cinematic-shell")).toHaveCSS("--selection-seed", "#654321");
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("estabrak_cart_v1") || "[]").length)).toBe(1);
});
