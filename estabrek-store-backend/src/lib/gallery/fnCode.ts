/**
 * Ready calculations: one code step each, with tests that show what it gives back (they run before
 * every publish, and in the gallery's own test). Each answers a call from a shop page or an app
 * (`public`, a few dozen a minute), and another function can call it too.
 */
import { L, fnEntry, i, on, s, type GalleryEntry } from "./kit.js";

type T = { id: string; name: string; input: Record<string, unknown>; value: unknown };
/** A calculation: its inputs, its code (it reads input.x and returns the answer), and its tests. */
function calc(o: { key: string; name: ReturnType<typeof L>; note: ReturnType<typeof L>; fnName: string; inputs: ReturnType<typeof i.text>[]; code: string; tests: T[]; slug?: string; category?: "utilities" | "finance" | "operations" }) {
  const give = Object.fromEntries(o.inputs.map((x) => [x.name, `{{input.${x.name}}}`]));
  return fnEntry({
    key: o.key,
    category: o.category ?? "utilities",
    name: o.name,
    note: o.note,
    fns: [
      {
        key: "calc",
        name: o.fnName,
        inputs: o.inputs,
        on: on.call(o.slug ?? o.key, "public", 60),
        do: [s.code(o.code, give, "answer"), s.ret("{{answer}}")],
        tests: o.tests.map((x) => ({ id: x.id, name: x.name, input: x.input, expect: { ok: true, value: x.value } })),
      },
    ],
  });
}
